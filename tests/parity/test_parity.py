"""Parity with the original TypeScript engine, using scripted dice (no seeds are compared).

The fixtures in ``fixtures/`` were generated by ``legacy-ts/engine/tools/gen-parity-fixtures.ts``.
Where the two ever disagree, ``docs/decisions.md`` says which side was right.
"""

from __future__ import annotations

from typing import Any

import pytest

from sahkku.engine import ScriptedDice, apply_action, throw_with
from sahkku.rules import VARIANTS

from .helpers import (
    action_from_key,
    build,
    cand_rows,
    canon,
    fixture_cands,
    hold_dice,
    legal_keys,
    load,
    options_from_ts,
    snapshot,
)

SETUPS = load("setup.json")
SCENARIOS = load("scenarios.json")
WALKS = load("walks.json")


def _fixture_legal(rows: list[Any]) -> list[str]:
    return sorted(canon(r) for r in rows)


@pytest.mark.parametrize("v", VARIANTS, ids=lambda v: v.id)
def test_variant_registry_matches_fixture_options(v: Any) -> None:
    fixture = next(s for s in SETUPS if s["variant"] == v.id)
    assert options_from_ts(fixture["options"]) == v.options


@pytest.mark.parametrize(
    "fx",
    SETUPS,
    ids=lambda f: (
        f"{f['variant']}-s{f['starter']}-m{int(f['miedutRequested'])}-e{int(f['equalOdds'])}"
    ),
)
def test_setup_matches(fx: dict[str, Any]) -> None:
    from sahkku.engine import new_game

    o = options_from_ts(fx["options"])
    s = new_game(o, starter=fx["starter"], miedut=fx["miedutRequested"], equal_odds=fx["equalOdds"])
    assert s.miedut == fx["miedut"]
    assert list(s.transforms) == fx["transforms"]
    for side in (0, 1):
        assert list(s.tracks[side].points) == fx["tracks"][side]["points"]
        assert s.tracks[side].loop_start == fx["tracks"][side]["loopStart"]
        assert list(s.home_slots[side]) == fx["homeSlots"][side]
    assert snapshot(s) == fx["snapshot"]


@pytest.mark.parametrize("fx", SCENARIOS, ids=lambda f: f["name"])
def test_scenario_matches(fx: dict[str, Any]) -> None:
    o = options_from_ts(fx["options"])
    s0 = build(o, fx["specs"], fx["current"], fx["starter"], fx["miedutRequested"], fx["equalOdds"])
    s = throw_with(s0, fx["dice"]) if fx["settle"] else hold_dice(s0, fx["dice"])
    assert snapshot(s) == fx["start"]
    if s.phase != "move":
        return
    assert legal_keys(s) == _fixture_legal(fx["legal"])
    assert cand_rows(s) == fixture_cands(fx["candidates"])
    for res in fx["results"]:
        t = apply_action(s, action_from_key(res["action"]))
        assert snapshot(t) == res["after"], res["action"]
        if t.phase != "over":
            assert legal_keys(t) == _fixture_legal(res["legalAfter"]), res["action"]


@pytest.mark.parametrize("i", range(len(WALKS)), ids=lambda i: f"{WALKS[i]['variant']}#{i}")
def test_scripted_walk_matches(i: int) -> None:
    fx = WALKS[i]
    o = options_from_ts(fx["options"])
    from sahkku.engine import new_game

    s = new_game(o, starter=fx["starter"], miedut=fx["miedutRequested"], equal_odds=fx["equalOdds"])
    assert snapshot(s) == fx["start"]
    for n, step in enumerate(fx["steps"]):
        where = f"{fx['variant']} walk {i} step {n} ({step['op']})"
        if step["op"] == "throw":
            s = throw_with(s, step["faces"])
        elif step["op"] == "move":
            assert legal_keys(s) == _fixture_legal(step["legal"]), where
            s = apply_action(s, action_from_key(step["action"]))
        else:
            assert legal_keys(s) == _fixture_legal(step["legal"]), where
            s = apply_action(s, action_from_key(step["action"]), ScriptedDice(step["faces"]))
        assert snapshot(s) == step["after"], where
